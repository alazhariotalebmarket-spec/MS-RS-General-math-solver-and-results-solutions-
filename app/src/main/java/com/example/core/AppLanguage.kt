object DigitHelper {
    private val banglaDigits = charArrayOf('০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯')

    fun toBanglaDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            if (ch in '0'..'9') {
                sb.append(banglaDigits[ch - '0'])
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    fun toEnglishDigits(input: String): String {
        val sb = StringBuilder(input.length)
        for (ch in input) {
            val idx = banglaDigits.indexOf(ch)
            if (idx >= 0) {
                sb.append(('0' + idx))
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }

    fun format(input: String, language: AppLanguage): String {
        return if (language == AppLanguage.BANGLA) toBanglaDigits(input) else toEnglishDigits(input)
    }

    fun formatDate(timestamp: Long, language: AppLanguage): String {
        val sdf = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.ENGLISH)
        val raw = sdf.format(Date(timestamp))
        return if (language == AppLanguage.BANGLA) toBanglaDigits(raw) else raw
    }

    fun formatShortDate(timestamp: Long, language: AppLanguage): String {
        val sdf = SimpleDateFormat("dd/MM/yyyy", Locale.ENGLISH)
        val raw = sdf.format(Date(timestamp))
        return if (language == AppLanguage.BANGLA) toBanglaDigits(raw) else raw
    }
}

